def run_paddle_ocr(image_path: str) -> List[Dict[str, Any]]:
    """
    Run OCR on an image using the best available local engine.
    Falls through: EasyOCR → PaddleOCR → PyMuPDF text layer.

    Returns list of dicts with: text, confidence, bbox, center_x, center_y.
    """
    if not os.path.exists(image_path):
        logger.error(f"Image not found: '{image_path}'")
        return []

    # Get image dimensions for normalization
    img_w, img_h = 1, 1
    try:
        import cv2
        img = cv2.imread(image_path)
        if img is not None:
            img_h, img_w = img.shape[:2]
    except Exception:
        try:
            from PIL import Image as PILImage
            pil = PILImage.open(image_path)
            img_w, img_h = pil.size
        except Exception:
            pass

    # ── Try EasyOCR first ─────────────────────────────────────────────────────
    try:
        logger.info(f"Running EasyOCR on '{image_path}'...")
        items = _run_easyocr(image_path, img_w, img_h)
        if items:
            logger.info(f"EasyOCR extracted {len(items)} text items.")
            return items
        else:
            logger.warning("EasyOCR returned 0 items. Trying PaddleOCR fallback.")
    except Exception as e:
        logger.warning(f"EasyOCR failed ({e}). Trying PaddleOCR.")

    # ── Try PaddleOCR ─────────────────────────────────────────────────────────
    try:
        logger.info(f"Running PaddleOCR on '{image_path}'...")
        items = _run_paddleocr(image_path, img_w, img_h)
        if items:
            logger.info(f"PaddleOCR extracted {len(items)} text items.")
            return items
        else:
            logger.warning("PaddleOCR returned 0 items. Trying PyMuPDF text layer.")
    except Exception as e:
        logger.warning(f"PaddleOCR failed ({e}). Trying PyMuPDF text layer.")

    # ── Try PyMuPDF text extraction ───────────────────────────────────────────
    try:
        logger.info(f"Trying PyMuPDF text layer extraction on '{image_path}'...")
        items = _run_pymupdf_text(image_path, img_w, img_h)
        if items:
            logger.info(f"PyMuPDF extracted {len(items)} text items.")
            return items
    except Exception as e:
        logger.warning(f"PyMuPDF text extraction failed ({e}).")

    logger.error(f"All OCR backends failed for '{image_path}'. Returning empty list.")
    return []


def format_paddle_results_for_llm(items: List[Dict[str, Any]]) -> str:
    """Format OCR results into an LLM-readable text block."""
    lines = [
        f"{item['text']} | conf={item['confidence']} | pos=({item['center_x']},{item['center_y']})"
        for item in items
    ]
    return "\n".join(lines)
